export function getDoctrineCost(key: 'economy' | 'warfare' | 'fortress', currentLevel: number): number {
  const base = key === 'economy' ? 110 : key === 'warfare' ? 135 : 125;
  return Math.round(base * Math.pow(1.72, currentLevel));
}
