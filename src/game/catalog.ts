export function getEraUnits(era: number): UnitDefinition[] {
  return UNITS.filter((u) => u.era === era).sort((a, b) => a.slotIndex - b.slotIndex);
}

export function getEraTurrets(era: number): TurretDefinition[] {
  return TURRETS.filter((t) => t.era === era).sort((a, b) => a.tier - b.tier);
}

export function getUnitById(id: string): UnitDefinition | undefined {
  return UNITS.find((u) => u.id === id);
}

export function getTurretById(id: string): TurretDefinition | undefined {
  return TURRETS.find((t) => t.id === id);
}

export function getDoctrineCost(key: 'economy' | 'warfare' | 'fortress', currentLevel: number): number {
  const base = key === 'economy' ? 120 : key === 'warfare' ? 150 : 140;
  return Math.round(base * Math.pow(1.85, currentLevel));
}
